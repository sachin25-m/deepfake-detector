def inspect_image_fixture(fpath: str, fname: str, pil_img: Image.Image) -> Tuple[bool, str]:
    """
    Identifies whether an image is a programmatic test fixture (e.g. geometric ellipse drawing)
    rather than a real-world photograph / authentic deepfake photograph.
    """
    lower_name = fname.lower()
    for prefix in KNOWN_SYNTHETIC_FIXTURE_PREFIXES:
        if lower_name.startswith(prefix):
            return True, "Programmatic test fixture from prepare_fake_dataset.py (geometric drawing / synthetic noise)"

    # Check for programmatic flat backgrounds with simple geometric shapes (e.g. solid color canvas)
    arr = np.array(pil_img)
    if arr.ndim == 3 and arr.shape[2] >= 3:
        # Check border pixels uniformity (typical of synthetic PIL drawings)
        top_edge = arr[0, :, :3]
        if np.std(top_edge) < 1.0:
            bottom_edge = arr[-1, :, :3]
            left_edge = arr[:, 0, :3]
            if np.std(bottom_edge) < 1.0 and np.std(left_edge) < 1.0:
                # Border is a solid flat programmatic background
                return True, "Programmatic canvas fixture (solid monochromatic border canvas)"

    return False, "OK"


class DatasetValidator:
    """
    Rigorous dataset validation: checks folders, readability, dimensions,
    duplicates via SHA-256, and separates synthetic test fixtures.
    """
    def __init__(self, real_dir: str, fake_dir: str, min_dim: int = 64):
        self.real_dir = real_dir
        self.fake_dir = fake_dir
        self.min_dim = min_dim
        self.seen_hashes: Dict[str, str] = {}
        self.valid_samples: List[Dict[str, Any]] = []
        self.synthetic_fixtures: List[Dict[str, Any]] = []
        self.skipped_samples: List[Dict[str, Any]] = []

    def validate(self):
        targets = [("REAL", self.real_dir), ("DEEPFAKE", self.fake_dir)]
        valid_extensions = (".jpg", ".jpeg", ".png", ".webp", ".bmp", ".tiff")

        for label, directory in targets:
            if not os.path.exists(directory):
                logger.warning(f"Directory not found: {directory}")
                continue

            for fname in sorted(os.listdir(directory)):
                fpath = os.path.join(directory, fname)
                if not os.path.isfile(fpath):
                    continue

                if not fname.lower().endswith(valid_extensions):
                    self.skipped_samples.append({
                        "file": fname,
                        "label": label,
                        "reason": f"Unsupported extension (allowed: {valid_extensions})"
                    })
                    continue

                # Read raw bytes
                try:
                    with open(fpath, "rb") as fh:
                        raw_bytes = fh.read()
                except Exception as e:
                    self.skipped_samples.append({
                        "file": fname,
                        "label": label,
                        "reason": f"File read error: {e}"
                    })
                    continue

                if len(raw_bytes) == 0:
                    self.skipped_samples.append({
                        "file": fname,
                        "label": label,
                        "reason": "Empty file (0 bytes)"
                    })
                    continue

                # Duplicate detection by SHA-256
                sha = hashlib.sha256(raw_bytes).hexdigest()
                if sha in self.seen_hashes:
                    self.skipped_samples.append({
                        "file": fname,
                        "label": label,
                        "reason": f"Duplicate file (matches {self.seen_hashes[sha]})"
                    })
                    continue
                self.seen_hashes[sha] = fname

                # Image readability & dimension checks
                try:
                    pil_img = Image.open(io.BytesIO(raw_bytes))
                    pil_img.verify()
                    # Re-open after verify()
                    pil_img = Image.open(io.BytesIO(raw_bytes))
                except Exception as e:
                    self.skipped_samples.append({
                        "file": fname,
                        "label": label,
                        "reason": f"Corrupted / unreadable image: {e}"
                    })
                    continue

                w, h = pil_img.size
                if w < self.min_dim or h < self.min_dim:
                    self.skipped_samples.append({
                        "file": fname,
                        "label": label,
                        "reason": f"Dimensions below minimum ({w}x{h} < {self.min_dim}x{self.min_dim})"
                    })
                    continue

                # Check if this sample is a synthetic test fixture
                is_fixture, fixture_reason = inspect_image_fixture(fpath, fname, pil_img)
                sample_record = {
                    "path": fpath,
                    "filename": fname,
                    "label": label,
                    "bytes": raw_bytes,
                    "size": (w, h),
                    "mode": pil_img.mode,
                    "sha256": sha[:10]
                }

                if is_fixture:
                    sample_record["fixture_reason"] = fixture_reason
                    self.synthetic_fixtures.append(sample_record)
                else:
                    self.valid_samples.append(sample_record)

        return self.valid_samples, self.synthetic_fixtures, self.skipped_samples


def run_pipeline_evaluation(samples: List[Dict[str, Any]], desc: str = "VALID SAMPLES"):
    """
    Executes the exact production pipeline on a set of samples and collects full telemetry.
    """
    results = []
    print(f"\nEvaluating {len(samples)} samples [{desc}] through Production Pipeline...")
    header = f"{'Filename':<30} | {'GT':<8} | {'ViT Pred':<8} | {'ViT%':>6} | {'Crop':<5} | {'ELA':>5} | {'FFT':>5} | {'Ensemble':<10} | {'Conf%':>6} | Status"
    print(header)
    print("-" * len(header))

    t_total = 0.0

    for s in samples:
        t0 = time.time()
        try:
            res = main.process_image_pipeline(s["bytes"], filename=s["filename"])
            elapsed = time.time() - t0
            t_total += elapsed
        except Exception as e:
            print(f"{s['filename']:<30} | {s['label']:<8} | ERROR: {e}")
            results.append({
                "sample": s,
                "error": str(e),
                "verdict": "ERROR",
                "correct": None
            })
            continue

        verdict = res["result"]
        conf = res["confidence"]
        details = res.get("details", {})
        vit_pred = details.get("vit_prediction", "N/A")
        vit_fake_p = details.get("vit_fake_probability", 0.0)
        is_cropped = details.get("face_crop_applied", False)
        crop_str = "YES" if is_cropped else "NO"
        fbd = details.get("forensic_breakdown", {})
        ela_val = fbd.get("ela_anomaly_score")
        fft_val = fbd.get("fft_spectral_score")
        ela_str = f"{ela_val:.2f}" if ela_val is not None else "N/A"
        fft_str = f"{fft_val:.2f}" if fft_val is not None else "N/A"

        gt = s["label"]
        if verdict == "INCONCLUSIVE":
            correct = None
            status_str = "INCON"
        elif verdict == gt:
            correct = True
            status_str = "PASS [OK]"
        else:
            correct = False
            status_str = "FP" if gt == "REAL" else "FN"

        print(f"{s['filename']:<30} | {gt:<8} | {vit_pred:<8} | {vit_fake_p:>5.1f}% | {crop_str:<5} | {ela_str:>5} | {fft_str:>5} | {verdict:<10} | {conf:>5.1f}% | {status_str}")

        results.append({
            "sample": s,
            "gt": gt,
            "verdict": verdict,
            "confidence": conf,
            "vit_prediction": vit_pred,
            "vit_fake_p": vit_fake_p,
            "is_cropped": is_cropped,
            "faces_detected": details.get("faces_detected", 0),
            "forensic_breakdown": fbd,
            "heuristic_action": details.get("heuristic_action", "none"),
            "correct": correct,
            "elapsed": elapsed
        })

    return results, t_total


def compute_metrics(results: List[Dict[str, Any]]):
    """
    Computes rigorous classification metrics with well-defined denominators.
    Inconclusive predictions are treated as non-decisive and excluded from accuracy
    (reported explicitly in coverage and inconclusive rate).
    """
    total = len(results)
    if total == 0:
        return {}

    decisive = [r for r in results if r.get("correct") is not None]
    inconclusive = [r for r in results if r.get("verdict") == "INCONCLUSIVE"]
    errors = [r for r in results if r.get("verdict") == "ERROR"]

    real_samples = [r for r in results if r.get("gt") == "REAL"]
    fake_samples = [r for r in results if r.get("gt") == "DEEPFAKE"]

    # Confusion Matrix (decisive predictions)
    tp = sum(1 for r in decisive if r["gt"] == "DEEPFAKE" and r["verdict"] == "DEEPFAKE")
    tn = sum(1 for r in decisive if r["gt"] == "REAL" and r["verdict"] == "REAL")
    fp = sum(1 for r in decisive if r["gt"] == "REAL" and r["verdict"] == "DEEPFAKE")
    fn = sum(1 for r in decisive if r["gt"] == "DEEPFAKE" and r["verdict"] == "REAL")

    # Inconclusive per-class
    incon_real = sum(1 for r in inconclusive if r["gt"] == "REAL")
    incon_fake = sum(1 for r in inconclusive if r["gt"] == "DEEPFAKE")

    # Calculations with explicit denominators
    accuracy = (tp + tn) / len(decisive) if len(decisive) > 0 else 0.0
    precision = tp / (tp + fp) if (tp + fp) > 0 else 0.0
    recall = tp / (tp + fn) if (tp + fn) > 0 else (0.0 if len(fake_samples) > 0 else None)
    f1 = 2 * precision * recall / (precision + recall) if (precision and recall and (precision + recall) > 0) else 0.0
    
    # Specificity / True Negative Rate on real photos
    decisive_real = tn + fp
    tnr = tn / decisive_real if decisive_real > 0 else 0.0
    fpr = fp / decisive_real if decisive_real > 0 else 0.0
    fnr = fn / (fn + tp) if (fn + tp) > 0 else 0.0

    coverage = len(decisive) / total * 100.0 if total > 0 else 0.0
    inconclusive_rate = len(inconclusive) / total * 100.0 if total > 0 else 0.0

    return {
        "total": total,
        "decisive_count": len(decisive),
        "inconclusive_count": len(inconclusive),
        "error_count": len(errors),
        "coverage": coverage,
        "inconclusive_rate": inconclusive_rate,
        "tp": tp, "tn": tn, "fp": fp, "fn": fn,
        "incon_real": incon_real, "incon_fake": incon_fake,
        "total_real": len(real_samples),
        "total_fake": len(fake_samples),
        "accuracy": accuracy,
        "precision": precision,
        "recall": recall,
        "f1": f1,
        "tnr": tnr,
        "fpr": fpr,
        "fnr": fnr
    }


